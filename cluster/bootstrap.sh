#!/usr/bin/env bash
# Bootstrap a single-node k3s cluster with kube-prometheus-stack and KEDA.
#
# Tested on Ubuntu 26.04 LTS, 4 vCPU / 8 GB. Idempotent: safe to re-run.
#
# Environment overrides (all optional):
#   K3S_VERSION          pin k3s release (default: latest stable)
#   KPS_CHART_VERSION    pin kube-prometheus-stack chart (default: latest)
#   KEDA_CHART_VERSION   pin keda chart (default: latest)
#   PROM_RETENTION       Prometheus retention (default: 30d)
#   PROM_SCRAPE_INTERVAL Prometheus scrape interval (default: 15s)
#
# The Grafana admin password is generated at install time and stored only in
# the Kubernetes Secret monitoring/monitoring-grafana. Retrieve it with
# ./grafana-password.sh. Installed versions are written to versions.lock.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
K3S_VERSION="${K3S_VERSION:-}"
KPS_CHART_VERSION="${KPS_CHART_VERSION:-}"
KEDA_CHART_VERSION="${KEDA_CHART_VERSION:-}"
PROM_RETENTION="${PROM_RETENTION:-30d}"
PROM_SCRAPE_INTERVAL="${PROM_SCRAPE_INTERVAL:-15s}"

log() { printf '\n==> %s\n' "$*"; }

require_root() {
  if [[ "$(id -u)" -ne 0 ]]; then
    echo "bootstrap.sh must run as root (k3s installs system services)" >&2
    exit 1
  fi
}

install_k3s() {
  if command -v k3s >/dev/null 2>&1; then
    log "k3s already installed: $(k3s --version | head -n1)"
    return
  fi
  log "Installing k3s ${K3S_VERSION:-latest}"
  curl -sfL https://get.k3s.io \
    | INSTALL_K3S_VERSION="${K3S_VERSION}" INSTALL_K3S_EXEC="--disable traefik" sh -
  mkdir -p "${HOME}/.kube"
  cp /etc/rancher/k3s/k3s.yaml "${HOME}/.kube/config"
  chmod 600 "${HOME}/.kube/config"
}

install_helm() {
  if command -v helm >/dev/null 2>&1; then
    log "helm already installed: $(helm version --short)"
    return
  fi
  log "Installing helm"
  curl -fsSL https://raw.githubusercontent.com/helm/helm/main/scripts/get-helm-3 | bash
}

add_repos() {
  log "Adding Helm repositories"
  helm repo add prometheus-community https://prometheus-community.github.io/helm-charts >/dev/null
  helm repo add kedacore https://kedacore.github.io/charts >/dev/null
  helm repo update >/dev/null
}

install_monitoring() {
  log "Installing kube-prometheus-stack"
  local version_flag=()
  [[ -n "${KPS_CHART_VERSION}" ]] && version_flag=(--version "${KPS_CHART_VERSION}")

  # Generate the Grafana admin password once; reuse on re-runs.
  local grafana_password
  if kubectl -n monitoring get secret monitoring-grafana >/dev/null 2>&1; then
    grafana_password="$(kubectl -n monitoring get secret monitoring-grafana \
      -o jsonpath='{.data.admin-password}' | base64 -d)"
  else
    grafana_password="$(openssl rand -base64 24 | tr -d '/+=' | cut -c1-24)"
  fi

  helm upgrade --install monitoring prometheus-community/kube-prometheus-stack \
    --namespace monitoring --create-namespace \
    "${version_flag[@]}" \
    --set grafana.adminPassword="${grafana_password}" \
    --set prometheus.prometheusSpec.retention="${PROM_RETENTION}" \
    --set prometheus.prometheusSpec.scrapeInterval="${PROM_SCRAPE_INTERVAL}" \
    --set alertmanager.enabled=false \
    --wait --timeout 10m
}

install_keda() {
  log "Installing KEDA"
  local version_flag=()
  [[ -n "${KEDA_CHART_VERSION}" ]] && version_flag=(--version "${KEDA_CHART_VERSION}")
  helm upgrade --install keda kedacore/keda \
    --namespace keda --create-namespace \
    "${version_flag[@]}" \
    --wait --timeout 5m
}

write_lockfile() {
  log "Recording installed versions to versions.lock"
  {
    echo "# Generated by bootstrap.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
    echo "k3s=$(k3s --version | head -n1 | awk '{print $3}')"
    echo "kubernetes=$(kubectl version -o json | python3 -c 'import json,sys;print(json.load(sys.stdin)["serverVersion"]["gitVersion"])')"
    echo "helm=$(helm version --template '{{.Version}}')"
    echo "kube-prometheus-stack=$(helm -n monitoring list -o json | python3 -c 'import json,sys;print([r for r in json.load(sys.stdin) if r["name"]=="monitoring"][0]["chart"])')"
    echo "keda=$(helm -n keda list -o json | python3 -c 'import json,sys;print([r for r in json.load(sys.stdin) if r["name"]=="keda"][0]["chart"])')"
  } > "${SCRIPT_DIR}/versions.lock"
  cat "${SCRIPT_DIR}/versions.lock"
}

verify() {
  log "Verifying cluster"
  kubectl wait --for=condition=Ready pods --all -A --timeout=300s
  kubectl get nodes -o wide
  kubectl top nodes || echo "metrics-server not ready yet; retry 'kubectl top nodes' in a minute"
}

main() {
  require_root
  install_k3s
  install_helm
  add_repos
  install_monitoring
  install_keda
  write_lockfile
  verify
  log "Done. Grafana password: ./grafana-password.sh"
}

main "$@"
